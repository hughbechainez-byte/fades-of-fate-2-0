/* Post-entity overlay: visible pose identity plus a 12-bit barcode. */
int demo_barcode_bit(int value, int bit)
{
    int divisor;
    divisor = 1;
    while(bit > 0)
    {
        divisor = divisor * 2;
        bit = bit - 1;
    }
    return (value / divisor) % 2;
}

